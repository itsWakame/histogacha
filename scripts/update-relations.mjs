const esc = (s) => "'" + String(s).replace(/'/g, "''") + "'"
const arr = (a) => 'ARRAY[' + a.map(esc).join(', ') + ']'

let stmts = []
for (const [id, [rels, notes]] of Object.entries(R)) {
  if (rels.length !== notes.length) throw new Error('id ' + id + ' length mismatch')
  stmts.push(`(${Number(id)}, ${arr(rels)}, ${arr(notes)})`)
}

mkdirSync('data', { recursive: true })
const CH = 10
for (let i = 0; i * CH < stmts.length; i++) {
  const rows = stmts.slice(i * CH, i * CH + CH)
  const sql =
    'UPDATE figures f SET relations = v.rels, rel_notes = v.notes\n' +
    'FROM (VALUES\n  ' + rows.join(',\n  ') + '\n) AS v(id, rels, notes)\n' +
    'WHERE f.id = v.id;'
  writeFileSync(`data/rel-part${i + 1}.sql`, sql)
}
